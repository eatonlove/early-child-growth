function entity(id: string): BaseEntity {
  return { id, tenantId: TENANT_ID, createdAt: CREATED_AT, updatedAt: CREATED_AT, createdBy: "knowledge-editor", version: 1 };
}

function makeGuideCard(goal: GuideGoalDefinition, grade: Grade): KnowledgeCard {
  const meta = gradeMeta[grade];
  const expectations = goal.expectations[grade];
  const code = `GUIDE-${goal.code}-${meta.suffix}`;
  const requirements = goal.evidenceRequirements ?? defaultEvidenceRequirements;
  return {
    ...entity(`knowledge-${code.toLowerCase()}`),
    code,
    kind: "指南年龄参照",
    source: "《3-6岁儿童学习与发展指南》",
    sourceVersion: GUIDE_SOURCE_VERSION,
    sourceUrl: GUIDE_SOURCE_URL,
    domain: goal.domain,
    subdomain: goal.subdomain,
    goalNumber: goal.goalNumber,
    grade,
    ageBand: meta.ageBand,
    title: goal.title,
    officialExpectations: expectations,
    observableBehaviors: [
      ...goal.gameCues,
      ...expectations.map((item) => `年龄段参照：${item}`),
    ],
    applicability: goal.applicability ?? "游戏直接观察",
    evidenceRequirements: requirements,
    assessmentGuidance: [
      "年龄段表现是该年龄段末期幼儿发展的大致合理期望，不是统一考试的及格线。",
      "一次观察最多支持“已观察到相关表现”或“部分证据”，不能据此判断稳定达到或未达到。",
      "形成较稳定判断需跨时间、跨情境，并结合幼儿独立表现与支持后表现。",
      "当证据不一致时保留差异，优先补充观察，不用分数平均掉真实情境。",
    ],
    misunderstandingWarning: goal.warning ?? "不能把缺少本次证据写成幼儿不会，也不能将成人提示后完成等同于幼儿独立稳定表现。",
    supportSuggestions: [goal.supports[0], goal.supports[1], goal.supports[2], meta.support],
    responseStrategies: {
      经验支持: [goal.supports[0], meta.support],
      材料支持: [goal.supports[1]],
      活动支持: [goal.supports[2]],
    },
    nextObservationPrompts: [
      `下一次在相近情境中，${grade}幼儿是否再次出现与“${goal.title}”相关的表现？`,
      "该表现是幼儿独立出现，还是在同伴、材料或教师支持后出现？",
      "更换材料、伙伴或场地后，相关经验是否仍能被使用？",
    ],
    keywords: [...goal.keywords, goal.title, goal.subdomain, goal.domain],
  };
}

